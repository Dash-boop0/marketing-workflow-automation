#!/usr/bin/env node
// Builds n8n/marketing-workflow.json from the same pure modules the web app and CLI use.
// The library files are concatenated (import lines removed, "export " keywords stripped) into one n8n Code node,
// so the n8n workflow runs exactly the same validation/normalisation/dedupe/rules/task logic.
// Usage: node scripts/build-n8n.js   (or npm run build:n8n)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIB_ORDER = ['csv', 'hash', 'dates', 'normalise', 'validate', 'dedupe', 'rules', 'tasks', 'outputs', 'pipeline'];

export function buildCodeNodeSource() {
  const parts = ['// AUTO-GENERATED by scripts/build-n8n.js from src/lib/*.js. Do not edit here; edit src/lib and rebuild.',
    '// Mock messaging only: this code never sends anything; it returns files and "would send" message records.', ''];
  for (const name of LIB_ORDER) {
    const src = fs.readFileSync(path.join(ROOT, 'src/lib', `${name}.js`), 'utf8');
    const body = src
      .split('\n')
      .filter((line) => !/^import\s.+;\s*$/.test(line))
      .map((line) => line.replace(/^export (?=(async )?(function|const|class|let)\b)/, ''))
      .join('\n');
    if (/^\s*(import|export)\s/m.test(body)) throw new Error(`src/lib/${name}.js has an import/export form the n8n builder cannot inline`);
    parts.push(`// ---------- src/lib/${name}.js ----------`, body.trim(), '');
  }
  parts.push(
    '// ---------- n8n entry point ----------',
    "const cfg = $('Config').first().json;",
    'const rules = JSON.parse(cfg.rulesJson);',
    'const csvText = String($input.first().json.data ?? \'\');',
    "const inputName = String(cfg.inputPath || 'leads.csv').split(/[\\\\/]/).pop();",
    'const result = runPipeline({ csvText, rules, today: cfg.runDate, inputName });',
    "const items = Object.entries(result.outputs).map(([fileName, content]) => ({ json: { _kind: 'file', fileName, content } }));",
    "for (const m of result.messages) items.push({ json: { _kind: 'mock_message', ...m } });",
    "if (result.fatal) items.push({ json: { _kind: 'run_stopped', message: `Run stopped (${result.fatal.code}): ${result.fatal.message}` } });",
    'return items;',
    '',
  );
  return parts.join('\n');
}

function switchRule(value, outputKey) {
  return {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
      conditions: [{ leftValue: '={{ $json._kind }}', rightValue: value, operator: { type: 'string', operation: 'equals' } }],
      combinator: 'and',
    },
    renameOutput: true,
    outputKey,
  };
}

